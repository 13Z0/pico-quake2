#!/usr/bin/env python3
"""Generates the savegame name tables for the game module.

Savegames store function pointers (think, touch, pain, ...) and monster animation
tables (mmove_t) by name rather than as code addresses, so a savegame keeps working
after the firmware is rebuilt. This script scans game/*.c for

  - every function whose first parameter is "edict_t *" (the shape of every callback
    stored in an edict), and
  - every file-scope "mmove_t name = ..." definition,

and writes a C file with prototypes and two tables sorted by name.

    python3 tools/gen_savetables.py <src/quake2/game> <output.c>

A callback-shaped function that is static cannot be referenced from the table; the
script stops with an error so the function can be made non-static.
"""
import re
import sys
from pathlib import Path

FUNC_RE = re.compile(
    r"^(static\s+)?((?:const\s+)?(?:void|qboolean|int|float|edict_t\s*\*|char\s*\*|gitem_t\s*\*))\s*"
    r"(\w+)\s*\(\s*(edict_t\s*\*[^)]*)\)\s*$")
MMOVE_RE = re.compile(r"^mmove_t\s+(\w+)\s*=")
# conditionals that are false in this port's builds; any other #if counts as true
FALSE_IF_RE = re.compile(r"^#\s*(if\s+0\b|ifdef\s+(_WIN32|WIN32|DEBUG)\b|if\s+defined[\s(]*(_WIN32|WIN32|_M_IX86)\b)")


def active_lines(lines):
    """Yields (index, line) for lines outside preprocessor branches that are off."""
    stack = []      # one bool per open conditional: is this branch active
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith("#"):
            d = s[1:].lstrip()
            if d.startswith(("if", "ifdef", "ifndef")):
                stack.append(not FALSE_IF_RE.match(s))
                continue
            if d.startswith(("else", "elif")) and stack:
                stack[-1] = not stack[-1]
                continue
            if d.startswith("endif") and stack:
                stack.pop()
                continue
        if all(stack):
            yield i, line


def scan(game_dir):
    funcs, mmoves, errors = {}, {}, []
    for path in sorted(Path(game_dir).glob("*.c")):
        lines = path.read_text(errors="replace").splitlines()
        for i, line in active_lines(lines):
            m = FUNC_RE.match(line)
            if m:
                # a definition: the next non-blank line opens the body
                rest = [l for l in lines[i + 1:i + 4] if l.strip()]
                if not rest or not rest[0].lstrip().startswith("{"):
                    continue
                name = m.group(3)
                if m.group(1):
                    errors.append(f"{path.name}:{i + 1}: static callback-shaped function {name}")
                    continue
                proto = f"{m.group(2).strip()} {name} ({m.group(4).strip()});"
                if name in funcs and funcs[name] != proto:
                    errors.append(f"{path.name}:{i + 1}: {name} defined twice")
                funcs[name] = proto
                continue
            m = MMOVE_RE.match(line)
            if m:
                mmoves[m.group(1)] = path.name
    return funcs, mmoves, errors


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    funcs, mmoves, errors = scan(sys.argv[1])
    if errors:
        sys.exit("gen_savetables.py: " + "\n".join(errors))
    out = ["// Generated by tools/gen_savetables.py from game/*.c. Do not edit.",
           '#include "g_local.h"', ""]
    out += [funcs[n] for n in sorted(funcs)]
    out.append("")
    out += [f"extern mmove_t {n};" for n in sorted(mmoves)]
    out += ["", "const savefunc_t g_savefuncs[] =", "{"]
    out += [f'\t{{"{n}", (void *){n}}},' for n in sorted(funcs)]
    out += ["};", f"const int g_numsavefuncs = {len(funcs)};", "",
            "const savemmove_t g_savemmoves[] =", "{"]
    out += [f'\t{{"{n}", &{n}}},' for n in sorted(mmoves)]
    out += ["};", f"const int g_numsavemmoves = {len(mmoves)};", ""]
    Path(sys.argv[2]).write_text("\n".join(out))
    print(f"gen_savetables.py: {len(funcs)} functions, {len(mmoves)} mmoves -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
